"""
akademisyenler.csv'deki unileri sehir_cikar ile test eder.
Sadece GERCEKTEN yanlis (yani tabloda bulunamayan) kayitlari gosterir.
"""
import csv, sys
sys.path.insert(0, ".")
from uret_csv import sehir_cikar, _norm, UNI_SEHIR_NORM

def sehir_ve_kaynak(uni):
    k = _norm(uni)
    if k in UNI_SEHIR_NORM:
        return UNI_SEHIR_NORM[k], "TABLO"
    for tk, sehir in UNI_SEHIR_NORM.items():
        if k in tk or tk in k:
            return sehir, "KISMI"
    parcalar = uni.strip().split()
    return (parcalar[0] if parcalar else ""), "GERCEK_FALLBACK"

uniler = {}
try:
    with open("akademisyenler.csv", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            uni = row.get("universite", "").strip()
            if uni and uni not in uniler:
                uniler[uni] = sehir_ve_kaynak(uni)
except FileNotFoundError:
    print("akademisyenler.csv bulunamadi, ornek test yapiliyor...")
    test_uniler = [
        "Türk-Alman Üni\u0307versi\u0307tesi\u0307",
        "Gebze Tekni\u0307k Üni\u0307versi\u0307tesi\u0307",
        "Boğazi\u0307çi\u0307 Üni\u0307versi\u0307tesi\u0307",
        "Aksaray Üni\u0307versi\u0307tesi\u0307",
        "Batman Üni\u0307versi\u0307tesi\u0307",
    ]
    for u in test_uniler:
        uniler[u] = sehir_ve_kaynak(u)

print(f"{'UNİVERSİTE':<65} {'ŞEHİR':<20} KAYNAK")
print("-" * 100)
gercek_fallback = 0
for uni, (sehir, kaynak) in sorted(uniler.items()):
    isaretli = "  <<< TABLO YOK!" if kaynak == "GERCEK_FALLBACK" else ""
    if kaynak == "GERCEK_FALLBACK":
        gercek_fallback += 1
    print(f"{uni:<65} {sehir:<20} {kaynak}{isaretli}")

print(f"\nToplam: {len(uniler)} | Tabloda yok (gercek sorun): {gercek_fallback}")